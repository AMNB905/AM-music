package com.am.music.ui.theme

import androidx.compose.ui.unit.dp

/**
 * 全 App 的尺寸口径。
 *
 * 之前各页面自己写 dp：标题有的从 24 起、有的从 14 起；歌曲行左边 24 / 16 / 14 三种；
 * 列表行的上下 8 / 9 / 11 混着用。单看每一页都还行，一页页翻过去就会觉得「内容在漂」。
 *
 * 这里只定四件事，凡是「页面的骨骼」都按这四个来，组件内部的细节尺寸不受限：
 * 1. 页面左右一律 24dp —— 标题、列表行、骨架的第一列都在同一条线上；
 * 2. 标题块：上 20dp、下 6dp，右侧有按钮时留 16dp；
 * 3. 歌曲行：左右 24dp、上下 9dp，封面 48dp —— 所有列表（在线 / 本地 / 榜单 / 歌单 / 队列 / 喜欢 / 最近）一致；
 * 4. 圆角两档：封面与输入框 2dp，浮起来的表面（浮岛 / 卡片）20dp。
 */
object Layout {

    /** 页面左右留白：标题、歌曲行、骨架图的第一列都从这条线开始。 */
    val Gutter = 24.dp

    /** 标题块距状态栏 / 上一块内容的高度。 */
    val HeaderTop = 20.dp

    /** 标题块下方留白：让下面的列表不至于贴着标题。 */
    val HeaderBottom = 6.dp

    /** 标题右侧给按钮留的位置（没有按钮时用 [Gutter]）。 */
    val HeaderEnd = 16.dp

    /** 歌曲行上下留白。 */
    val RowVertical = 9.dp

    /** 封面小图 / 网格缩略图 / 输入框的圆角：整个 App 是「直角 + 微圆」的调子。 */
    val ArtRadius = 2.dp

    /** 浮起来的表面（浮岛、引导卡片）。 */
    val SurfaceRadius = 20.dp
}
